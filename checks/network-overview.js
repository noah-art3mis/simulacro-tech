async page => {
  const home=new URL('/',page.url()).href;
  await page.goto(home);
  if(await page.locator('.hero .overview-control').count())throw new Error('The big-picture control belongs only in the second network window');
  const button=page.locator('.interlude .overview-control');
  if(!await button.count())throw new Error('The network must offer a See the big picture control');
  await page.evaluate(()=>{const ctx=document.querySelector('#network').getContext('2d'),clear=ctx.clearRect.bind(ctx);window.__overviewDraws=0;ctx.clearRect=(...args)=>{window.__overviewDraws++;return clear(...args)}});
  await button.focus();await page.keyboard.press('Enter');
  const overview=page.getByRole('group',{name:'Network overview',exact:true});
  await overview.waitFor({state:'visible'});
  if(await overview.locator('[data-overview-label]').count())throw new Error('The ordered structures must not have visible category names');
  const canvas=page.locator('#network');
  if(await canvas.getAttribute('data-structure-source')!=='network')throw new Error('The big picture must reveal the actual network, not a replacement diagram');
  await page.waitForFunction(()=>document.querySelector('#network').dataset.view==='overview');
  if(Number(await canvas.getAttribute('data-structure-nodes'))!==6420||Number(await canvas.getAttribute('data-structure-edges'))!==7464)throw new Error('The overview must retain the original graph nodes and connections');
  if(await page.locator('canvas').count()!==1)throw new Error('Overview must reuse the existing canvas');
  await page.waitForFunction(()=>document.querySelector('#network').dataset.view==='overview');
  await page.waitForTimeout(1500);
  const still=await canvas.getAttribute('data-camera-phase');
  const draws=await page.evaluate(()=>window.__overviewDraws);
  await page.waitForTimeout(200);
  if(await canvas.getAttribute('data-camera-phase')!==still)throw new Error('The big picture must settle so it can be read');
  if(await page.evaluate(()=>window.__overviewDraws)!==draws)throw new Error('The settled overview must stop drawing frames');
  await page.getByRole('button',{name:'Back to the network',exact:true}).first().click();
  await page.waitForFunction(()=>document.querySelector('#network').dataset.view==='network');
  if(await overview.isVisible())throw new Error('Overview labels must leave when returning to the network');
  await page.waitForTimeout(1500);
  const moving=await canvas.getAttribute('data-camera-phase');
  await page.waitForTimeout(200);
  if(await canvas.getAttribute('data-camera-phase')===moving)throw new Error('Returning must restore the moving network');
  await page.getByRole('button',{name:'Pause motion',exact:true}).first().click();
  await page.getByRole('button',{name:'See the big picture',exact:true}).first().click();
  await page.waitForTimeout(1500);
  await page.getByRole('button',{name:'Back to the network',exact:true}).first().click();
  await page.waitForTimeout(1500);
  const paused=await canvas.getAttribute('data-camera-phase');
  await page.waitForTimeout(200);
  if(await canvas.getAttribute('data-camera-phase')!==paused)throw new Error('The overview toggle must preserve the previous pause state');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.getByRole('button',{name:'See the big picture',exact:true}).first().click();
  await page.waitForTimeout(50);
  if(await canvas.getAttribute('data-view')!=='overview')throw new Error('Reduced motion must switch to the overview immediately');
  await page.emulateMedia({reducedMotion:'no-preference'});
  return {overview:'unlabelled structures, settled',canvas:'reused',return:'moving network restored',pause:'preserved',reducedMotion:'immediate'};
}
